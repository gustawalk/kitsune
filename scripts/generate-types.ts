// Generate IPC data models from the restricted, explicit Rust contract vocabulary.
// Unsupported Rust syntax fails generation rather than silently guessing a type.
import { readFileSync, writeFileSync } from "node:fs";
const source = readFileSync(
  new URL("../src-tauri/src/model.rs", import.meta.url),
  "utf8",
).replace(/\r\n?/g, "\n");
function splitFields(value: string) {
  const fields: string[] = [];
  let depth = 0,
    start = 0;
  for (let i = 0; i < value.length; i++) {
    if (value[i] === "<") depth++;
    if (value[i] === ">") depth--;
    if (value[i] === "," && depth === 0) {
      fields.push(value.slice(start, i));
      start = i + 1;
    }
  }
  fields.push(value.slice(start));
  return fields;
}
function type(rust: string): string {
  const value = rust.trim();
  const primitive: Record<string, string> = {
    String: "string",
    bool: "boolean",
    i64: "number",
    u64: "number",
    u16: "number",
    u32: "number",
    "serde_json::Value": "unknown",
  };
  if (primitive[value]) return primitive[value];
  if (value.startsWith("Option<")) return `${type(value.slice(7, -1))} | null`;
  if (value.startsWith("Vec<")) return `Array<${type(value.slice(4, -1))}>`;
  if (value.startsWith("BTreeMap<")) {
    const [key, val] = splitFields(value.slice(9, -1));
    return `Record<${type(key)}, ${type(val)}>`;
  }
  if (/^[A-Z][A-Za-z]+$/.test(value)) return value;
  throw new Error(`Unsupported Rust contract type: ${value}`);
}
let output =
  "// Generated by bun run types:generate from src-tauri/src/model.rs. Do not edit.\n";
const enumBody = source.match(/pub enum Value\s*\{([\s\S]*?)\n\}/)?.[1];
if (!enumBody) throw new Error("Missing Value enum");
const variants = enumBody
  .split(",")
  .map((s) => s.trim())
  .filter(Boolean);
output += `export type Value = ${variants
  .map((v) => {
    const match = v.match(/^(\w+)(?:\((\w+)\))?$/);
    if (!match) throw new Error(`Unsupported enum variant ${v}`);
    return `{ kind: '${match[1][0].toLowerCase()}${match[1].slice(1)}'${match[2] ? `; value: ${type(match[2])}` : ""} }`;
  })
  .join(" | ")};\n`;
for (const match of source.matchAll(/pub struct (\w+)\s*\{([^}]+)\}/g)) {
  const [, name, body] = match;
  const fields = splitFields(body).filter((s) => s.includes("pub "));
  output += `export interface ${name} {\n`;
  for (const field of fields) {
    if (field.includes("skip_serializing")) continue;
    const pair = field.match(/pub\s+(\w+)\s*:\s*([\s\S]+)$/);
    if (!pair) throw new Error(`Unsupported field ${field}`);
    const fieldName = pair[1].replace(/_([a-z])/g, (_, c: string) =>
      c.toUpperCase(),
    );
    output += `  ${fieldName}: ${type(pair[2])};\n`;
  }
  output += "}\n";
}
const target = new URL("../src/lib/generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replace(/\r\n?/g, "\n") !== output)
    throw new Error(
      "Rust/TypeScript contracts differ. Run bun run types:generate.",
    );
} else writeFileSync(target, output);
